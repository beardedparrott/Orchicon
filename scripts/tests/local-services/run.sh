#!/usr/bin/env bash
# ============================================================================
# Offline harness for the LOCAL SERVICES inner loop (no Docker, no database).
#
# WHY THIS EXISTS. Removing the instance container from the inner loop breaks
# `make run`, `make migrate` and `make rls-check` TOGETHER, and every one of those
# failures is quiet:
#
#   1. A LITERAL DSN THAT IS DEV'S PORT. DB_URL used to be
#      `postgres://…@localhost:5432/…` — dev's number, written down twice. Prod is
#      5433, so a prod checkout's `make migrate` applied prod's migrations to DEV's
#      database, successfully and silently. It is now DERIVED (scripts/container.sh
#      db-url), and this harness fails if a bare 5432 literal comes back.
#   2. A PER-INSTANCE PORT THAT IS NOT DERIVED. `orchicon services` and the DSN
#      must read the SAME table, or two instances bind one port (one instance's
#      plane then talks to the other's database).
#   3. AN UNDISCOVERABLE TARGET. `make help` is generated by an awk over `##`
#      comments, so a target added without one is invisible — which is how an
#      operator concludes the feature does not exist.
#
# WHAT IS REAL HERE: scripts/container.sh's own functions and the Makefile's own
# variables, both EXECUTED (unlike the host-residency harness, which extracts by
# text because container.sh drives Docker). `services-port`/`db-url` are pure —
# they touch no engine — and `make -n` prints the recipe without running anything.
#
#   scripts/tests/local-services/run.sh
#
# Exits 0 only when every assertion passes.
# ============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${HERE}/../../.." && pwd)"
CONTAINER_SH="${REPO_ROOT}/scripts/container.sh"
MAKEFILE="${REPO_ROOT}/Makefile"

# The harness's own environment must not decide any case: an ambient override
# would make the per-instance assertions pass vacuously.
unset ORCHICON_POSTGRES_PORT ORCHICON_NATS_PORT ORCHICON_NATS_MONITOR_PORT 2>/dev/null || true
unset ORCHICON_INSTANCE 2>/dev/null || true

PASSED=0
FAILED=0

check() { # <label> <expected> <actual>
  if [ "$2" = "$3" ]; then
    printf '  \033[32mPASS\033[0m  %-56s %s\n' "$1" "$3"
    PASSED=$((PASSED + 1))
  else
    printf '  \033[31mFAIL\033[0m  %-56s want [%s] got [%s]\n' "$1" "$2" "$3"
    FAILED=$((FAILED + 1))
  fi
}

check_contains() { # <label> <needle> <haystack>
  case "$3" in
    *"$2"*) check "$1" "contains:$2" "contains:$2" ;;
    *)      check "$1" "contains:$2" "MISSING (got: $3)" ;;
  esac
}

# make_invoke <args...> — run `make` in the repo root and print ONLY its output.
#
# TWO THINGS ARE STRIPPED, and both are load-bearing because this harness runs in
# CI as a `make ci-go` prerequisite:
#
#   - MAKEFLAGS is CLEARED for the child. When this script is itself run BY make,
#     MAKEFLAGS carries `--print-directory` and the jobserver, so the child emits
#     `make[1]: Entering directory '...'` / `Leaving directory` lines AROUND the
#     recipe — and a `tail -1` then reads a directory banner instead of the
#     recipe, so every derived-DSN assertion fails with "MISSING" while the same
#     script passes when run by hand. (Measured: exactly that, 5 failures.)
#   - the Entering/Leaving banner is dropped defensively even with an environment
#     that forces it back (e.g. a wrapper that sets MAKEFLAGS after us).
make_invoke() {
  local out
  out="$(cd "$REPO_ROOT" && MAKEFLAGS= make "$@" 2>/dev/null)"
  printf '%s\n' "$out" | grep -vE "^make(\[[0-9]+\])?: (Entering|Leaving) directory"
}

echo "container.sh under test: ${CONTAINER_SH}"
echo "Makefile under test:     ${MAKEFILE}"
echo

# --- (i) PER-INSTANCE PORTS -------------------------------------------------
#
# dev 5432 / prod 5433 / test 5434 is the ONE authoritative table
# (cmd/orchicon/install_ports.go, container.sh:instance_info), and
# TestInstallPortDefaultsMatchContainerScript asserts the two agree. `services`
# must read that table rather than carry a third copy.
echo "(i) per-instance ports come from the one table"
check "services-port dev postgres"  5432 "$(bash "$CONTAINER_SH" services-port dev postgres)"
check "services-port prod postgres" 5433 "$(bash "$CONTAINER_SH" services-port prod postgres)"
check "services-port test postgres" 5434 "$(bash "$CONTAINER_SH" services-port test postgres)"
check "services-port dev nats"      4222 "$(bash "$CONTAINER_SH" services-port dev nats)"
check "services-port prod nats"     4223 "$(bash "$CONTAINER_SH" services-port prod nats)"
check "services-port dev nats-mon"  8222 "$(bash "$CONTAINER_SH" services-port dev nats-mon)"
check "services-port prod nats-mon" 8223 "$(bash "$CONTAINER_SH" services-port prod nats-mon)"
echo

# --- (ii) THE DERIVED DSN ---------------------------------------------------
echo "(ii) the DSN is derived from the port, per instance"
check_contains "db-url dev uses :5432"  ":5432/" "$(bash "$CONTAINER_SH" db-url dev)"
check_contains "db-url prod uses :5433" ":5433/" "$(bash "$CONTAINER_SH" db-url prod)"
check_contains "db-url test uses :5434" ":5434/" "$(bash "$CONTAINER_SH" db-url test)"
check "db-url prod (whole)" \
  "postgres://orchicon:orchicon@localhost:5433/orchicon?sslmode=disable" \
  "$(bash "$CONTAINER_SH" db-url prod)"
# An override must move BOTH the port and the DSN together — that is the whole
# reason for deriving rather than writing the literal down twice.
check "db-url follows ORCHICON_POSTGRES_PORT" \
  "postgres://orchicon:orchicon@localhost:6543/orchicon?sslmode=disable" \
  "$(ORCHICON_POSTGRES_PORT=6543 bash "$CONTAINER_SH" db-url dev)"
# An instance the table does not define must REFUSE rather than inherit dev's.
if bash "$CONTAINER_SH" db-url staging >/dev/null 2>&1; then
  check "db-url refuses an unknown instance" "nonzero exit" "exit 0"
else
  check "db-url refuses an unknown instance" "nonzero exit" "nonzero exit"
fi
echo

# --- (iii) THE MAKEFILE DERIVES IT TOO --------------------------------------
#
# `make -n` prints the recipe with variables expanded and RUNS NOTHING, so this
# checks the real Makefile without needing atlas or a database.
echo "(iii) the Makefile's DB_URL is derived, per instance"
migrate_dev="$(make_invoke -n migrate | tail -1)"
migrate_prod="$(make_invoke -n migrate instance=prod | tail -1)"
migrate_test="$(make_invoke -n migrate instance=test | tail -1)"
check_contains "make migrate defaults to dev (:5432)" ":5432/" "$migrate_dev"
check_contains "make migrate instance=prod (:5433)"    ":5433/" "$migrate_prod"
check_contains "make migrate instance=test (:5434)"    ":5434/" "$migrate_test"

# An explicit DB_URL must still win — the documented CI escape hatch.
explicit="$(make_invoke -n migrate DB_URL='postgres://u@h:9999/x' | tail -1)"
check_contains "an explicit DB_URL wins" "postgres://u@h:9999/x" "$explicit"

# rls-check takes the SAME derived value, or the gate checks a different database
# than migrate applied to.
rls="$(make_invoke -n rls-check | tail -1)"
check_contains "rls-check uses the derived DSN" ":5432/" "$rls"
echo

# --- (iv) NO BARE 5432 LITERAL IN THE MAKEFILE ------------------------------
#
# THE REGRESSION THIS PINS is the DSN literal coming back. A bare
# `localhost:5432` in the Makefile means the port is written down again instead of
# derived, and prod silently points at dev again.
echo "(iv) the Makefile carries no bare DSN literal"
# A bare literal is only legitimate INSIDE the derived DB_URL expression (the
# never-bash fallback) or inside a comment explaining the bug. Anywhere else —
# above all a second assignment — is the port written down again, and prod
# silently points at dev again.
bare_literals="$(grep -nE 'orchicon:orchicon@localhost:5432' "$MAKEFILE" \
  | grep -vE '^[0-9]+:#' | grep -vE '^[0-9]+:DB_URL' || true)"
check "the DSN literal appears only in DB_URL's derived fallback" "" "$bare_literals"
# The fallback is allowed to name 5432 — it is the never-bash fallback, not the
# resolution — but it must sit INSIDE the derived expression, not on its own.
derived_line="$(grep -n '^DB_URL' "$MAKEFILE" | head -1)"
check_contains "DB_URL's default is derived via db-url" "scripts/container.sh db-url" "$derived_line"
echo

# --- (v) THE NEW TARGETS ARE DISCOVERABLE -----------------------------------
#
# `make help` is an awk over the `##` comments, so a target without one is
# invisible to the operator — which is exactly how a shipped feature reads as
# missing.
echo "(v) the new targets appear in make help"
help_out="$(make_invoke help)"
check_contains "make help lists services"        "services"        "$help_out"
check_contains "make help lists services-down"   "services-down"   "$help_out"
check_contains "make help lists services-status" "services-status" "$help_out"
# ...and each of them actually carries a `##` comment (the awk's requirement).
for t in services services-down services-status local-services-test; do
  line="$(grep -nE "^${t}:" "$MAKEFILE" | head -1)"
  check_contains "target ${t} has a ## comment" "##" "$line"
done
echo

# --- (vi) TEST ISOLATION IS UNBROKEN ----------------------------------------
#
# `make test` must not start services (CI runs it against the container's DB),
# and its ambient-unset list must not have grown to swallow the opt-ins.
echo "(vi) the test target's contract is unbroken"
test_prereq="$(grep -nE '^test:' "$MAKEFILE" | head -1 | cut -d: -f2-)"
check_contains "make test has NO services prerequisite" "test: ## Run Go tests" "$test_prereq"
unset_line="$(grep -n 'ORCHICON_GUARD_FULLSEND ORCHICON_SERVE_STATE_DIR' "$MAKEFILE" | head -1)"
check_contains "the ambient-unset list is intact" "ORCHICON_GUARD_FULLSEND ORCHICON_SERVE_STATE_DIR" "$unset_line"
# ORCHICON_TEST_DSN is an OPT-IN and must never join the unset list.
case "$unset_line" in
  *ORCHICON_TEST_DSN*) check "ORCHICON_TEST_DSN is not unset" "absent" "PRESENT" ;;
  *)                   check "ORCHICON_TEST_DSN is not unset" "absent" "absent" ;;
esac
echo

# --- (vii) THE RUN PATH STARTS SERVICES FIRST -------------------------------
echo "(vii) make run starts the services first"
run_line="$(grep -nE '^run:' "$MAKEFILE" | head -1)"
check_contains "run depends on services" "run: services" "$run_line"
# ...AND THE PLANE MUST ADDRESS THE INSTANCE THE SERVICES STARTED. `make run` used
# to boot the plane with NO instance env, so `instance=prod` started prod's
# services on 5433 and then read config's dev defaults (5432) — a plane and a
# database belonging to two different instances, silently. The derived env is the
# fix, so it is pinned here rather than left to the recipe's comments.
run_body="$(sed -n '/^run: services/,/^[^ \t]/p' "$MAKEFILE")"
check_contains "run passes the derived DSN to the plane" 'ORCHICON_POSTGRES_DSN="$(DB_URL)"' "$run_body"
run_prod="$(make_invoke -n run instance=prod | tr -d '\n')"
case "$run_prod" in
  *":5433/"*) check "run derives prod's DSN from the port table" "contains::5433/" "contains::5433/" ;;
  *)          check "run derives prod's DSN from the port table" "contains::5433/" "MISSING (got: ${run_prod:0:200})" ;;
esac
check_contains "run derives NATS from the same table"      'services-port $(instance) nats' "$run_body"
check_contains "run sets the instance's data dir"          'orchicon-$(instance)'            "$run_body"
echo

# --- (viii) check-rls.sh HAS THE BINDIR RUNG --------------------------------
echo "(viii) check-rls.sh can reach a host-services psql"
check_contains "check-rls.sh probes the services bindir" "services/pg/bin}/psql" "$(cat "${REPO_ROOT}/scripts/check-rls.sh")"
echo

echo "----------------------------------------"
printf 'local-services: %d passed, %d failed\n' "$PASSED" "$FAILED"
[ "$FAILED" -eq 0 ] || exit 1
exit 0
